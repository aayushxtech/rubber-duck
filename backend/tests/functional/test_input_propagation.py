"""Tests for runtime input propagation, prompt construction, Python metadata generation, and safeguards."""

from datetime import UTC, datetime
from unittest.mock import MagicMock, patch
from uuid import UUID, uuid4

import pytest
from app.graph.nodes.ananlyze import analyze_node
from app.graph.state import GraphState
from app.schemas.analysis import DuckAnalysisContent
from app.schemas.request import DuckRequest
from app.services.parsed_response import ParsedResponse


def _dummy_content_response(analysis_text="Analyzed successfully"):
    content = DuckAnalysisContent(
        analysis=analysis_text,
        assumptions=["Assumption 1"],
        uncertainties=["Uncertainty 1"],
        needs_search=False,
    )
    return ParsedResponse(
        value=content,
        raw_text="{}",
        model="openai/gpt-oss-120b",
        attempts=1,
        success=True,
        errors=None,
    )


def test_analysis_id_generated_by_python_is_valid_uuid():
    """1. Analysis IDs are generated by Python and are valid UUIDs."""
    req = DuckRequest(
        req_id=uuid4(),
        req="Does entropy always increase in closed systems?",
        req_time=datetime.now(UTC),
        status="socratic",
    )
    state = GraphState(request=req)

    with patch(
        "app.graph.nodes.ananlyze.call_structured_llm",
        return_value=_dummy_content_response(),
    ):
        result_state = analyze_node(state)

    assert result_state.analysis is not None
    assert isinstance(result_state.analysis.analysis_id, UUID)
    assert result_state.analysis.analysis_id.version == 4


def test_analysis_timestamp_generated_by_python_timezone_aware():
    """2. Analysis timestamps are generated by Python and timezone-aware."""
    req = DuckRequest(
        req_id=uuid4(),
        req="Explain quantum entanglement verification.",
        req_time=datetime.now(UTC),
        status="socratic",
    )
    state = GraphState(request=req)

    before = datetime.now(UTC)
    with patch(
        "app.graph.nodes.ananlyze.call_structured_llm",
        return_value=_dummy_content_response(),
    ):
        result_state = analyze_node(state)
    after = datetime.now(UTC)

    assert result_state.analysis is not None
    ts = result_state.analysis.analysis_time
    assert isinstance(ts, datetime)
    assert ts.tzinfo is not None
    assert before <= ts <= after


def test_llm_prompt_contains_actual_user_question():
    """3. The LLM prompt contains the actual user question."""
    captured_prompts = []

    def mock_call_structured_llm(*, task_name, prompt, schema, **kwargs):
        captured_prompts.append(prompt)
        return _dummy_content_response()

    unique_question = "How does CRISPR-Cas9 target specific genomic loci?"
    req = DuckRequest(
        req_id=uuid4(),
        req=unique_question,
        req_time=datetime.now(UTC),
        status="socratic",
    )
    state = GraphState(request=req)

    with patch(
        "app.graph.nodes.ananlyze.call_structured_llm",
        side_effect=mock_call_structured_llm,
    ):
        analyze_node(state)

    assert len(captured_prompts) == 1
    assert unique_question in captured_prompts[0]


def test_unresolved_placeholders_rejected_before_llm_call():
    """4. Unresolved placeholders are rejected before the LLM call."""
    req = DuckRequest(
        req_id=uuid4(),
        req="Valid question",
        req_time=datetime.now(UTC),
        status="socratic",
    )
    state = GraphState(request=req)

    mock_llm = MagicMock()
    # If a prompt contains an unresolved placeholder, analyze_node must raise ValueError before calling LLM
    with patch("app.graph.nodes.ananlyze.call_structured_llm", mock_llm):
        # We can simulate a malformed prompt format injection or inspect safeguard check directly
        state.request.req = "{user_message}"
        with pytest.raises(
            ValueError, match="Unresolved \\{user_message\\} placeholder"
        ):
            analyze_node(state)

    # Verify LLM was never called
    mock_llm.assert_not_called()


def test_empty_or_whitespace_input_rejected():
    """5. Empty input is rejected."""
    # Test empty string in GraphState
    req_empty = DuckRequest(
        req_id=uuid4(),
        req="",
        req_time=datetime.now(UTC),
        status="socratic",
    )
    state_empty = GraphState(request=req_empty)
    with pytest.raises(ValueError, match="empty or whitespace-only"):
        analyze_node(state_empty)

    # Test whitespace-only string in GraphState
    req_ws = DuckRequest(
        req_id=uuid4(),
        req="   \n\t  ",
        req_time=datetime.now(UTC),
        status="socratic",
    )
    state_ws = GraphState(request=req_ws)
    with pytest.raises(ValueError, match="empty or whitespace-only"):
        analyze_node(state_ws)


def test_invalid_llm_responses_do_not_produce_successful_analysis():
    """6. Invalid LLM responses do not produce successful analyses."""
    req = DuckRequest(
        req_id=uuid4(),
        req="How do stars form?",
        req_time=datetime.now(UTC),
        status="socratic",
    )
    state = GraphState(request=req)

    # Failed provider response (success=False)
    failed_response = ParsedResponse(
        value=None,
        raw_text=None,
        model="openai/gpt-oss-120b",
        attempts=3,
        success=False,
        errors=["Permanent LLM call error: ProviderError"],
    )

    with patch(
        "app.graph.nodes.ananlyze.call_structured_llm", return_value=failed_response
    ), pytest.raises(RuntimeError, match="Analyze node failed"):
        analyze_node(state)

    assert state.analysis is None
